// Cyrillic letters drawn exactly as the Latin ones they look like.
const LOOKALIKES: Readonly<Record<string, string>> = {
  А: 'A',
  В: 'B',
  Е: 'E',
  К: 'K',
  М: 'M',
  Н: 'H',
  О: 'O',
  Р: 'P',
  С: 'C',
  Т: 'T',
  Х: 'X',
};

/** The face's size in dots, and the advance from one character to the next. */
export const GLYPH = { columns: 5, rows: 7, advance: 6 } as const;

/** The lit dots of `char` as `[column, row]` pairs; throws on a character the face lacks. */
export function glyph(char: string): ReadonlyArray<readonly [number, number]> {
  const rows = FACE[LOOKALIKES[char] ?? char];
  if (rows === undefined) {
    throw new Error(
      `The tape's dot face has no glyph for ${JSON.stringify(char)}`,
    );
  }
  const lit: Array<readonly [number, number]> = [];
  for (const [y, row] of rows.split(' ').entries()) {
    let x = 0;
    for (const dot of row) {
      if (dot === '#') lit.push([x, y]);
      x += 1;
    }
  }
  return lit;
}

// Every glyph in the face is a single UTF-16 unit, so a string's length is
// its count of characters.
/** How wide `text` is in dots, without the gap after its last character. */
export const dotsWide = (text: string): number =>
  text.length === 0 ? 0 : text.length * GLYPH.advance - 1;
