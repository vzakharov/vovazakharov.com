#!/bin/bash
# Attest: run `scripts/vet.sh all` on the pushed head and record the result as
# the PR's attestation comment, `@.claude/skills/finalize/SKILL.md` Step 7.
#
# The comment is written by the run that produced the verdict, so it can say no
# more than ran: green or red, the head and base it ran against, the run's link
# when `vet.sh all` printed a `vet: run <url>` line. It is sticky — found by its
# `<!-- finalize-attestation <sha> -->` marker and edited in place, never by
# `gh pr comment --edit-last`, which would overwrite whichever comment was last.
# The marker's SHA is what `.claude/costs/lib/finalized.py` parses.
#
# Stack-free: what `all` runs is each project's `vet.sh` to decide, and may be
# the bare run itself.
#
# Usage:
#   scripts/attest.sh [--note <file>]
#   scripts/attest.sh --no-vet <why> [--note <file>]
#
#   --note <file>   lines appended under the verdict, which the caller owns
#   --no-vet <why>  post the "none required" form, running nothing: why the diff
#                   has nothing to verify
#
# Exit codes:
#   0  - `vet.sh all` passed (or --no-vet) and the comment is up.
#   1  - `vet.sh all` failed (the comment says so), or a git/gh step failed.
#   2  - bad arguments, or a tree that differs from the pushed head.
set -uo pipefail

cd "$(dirname "$0")/.."

usage() {
  printf 'usage: scripts/attest.sh [--no-vet <why>] [--note <file>]\n' >&2
  exit 2
}

note="" no_vet=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --note) [ "$#" -ge 2 ] && [ -f "$2" ] || usage; note="$2"; shift 2 ;;
    --no-vet) [ "$#" -ge 2 ] && [ -n "$2" ] || usage; no_vet="$2"; shift 2 ;;
    *) usage ;;
  esac
done

branch=$(git branch --show-current)
head=$(git rev-parse HEAD)
pushed=$(git ls-remote origin "refs/heads/$branch" | cut -f1)
if [ -n "$(git status --porcelain)" ] || [ "$pushed" != "$head" ]; then
  printf 'attest: commit and push %s first — the attestation names the pushed head\n' "$branch" >&2
  exit 2
fi

pr=$(gh pr view --json number --jq .number) || exit 1
base=$(gh pr view --json baseRefName --jq .baseRefName) || exit 1
repo=$(gh repo view --json nameWithOwner --jq .nameWithOwner) || exit 1
git fetch -q origin "$base" || exit 1
base_line="\`$base\` @ $(git log -1 --format='%h "%s"' "origin/$base")"
short=$(git rev-parse --short HEAD)

mkdir -p tmp
status=0 url=""
if [ -z "$no_vet" ]; then
  log=tmp/attest-vet.log
  scripts/vet.sh all 2>&1 | tee "$log" || status=1
  url=$(sed -n 's/^vet: run //p' "$log" | tail -n1)
fi

body=tmp/attest-comment.md
{
  printf '<!-- finalize-attestation %s -->\n\n' "$head"
  if [ -n "$no_vet" ]; then
    printf '### Attestation — none required\n\n'
    printf '%s (`%s`) against %s.\n\n' "$short" "$branch" "$base_line"
    printf 'Finalized in `no vet` mode: %s. `scripts/vet.sh all` was skipped rather than run green.\n' "$no_vet"
  else
    verdict='**green**'
    ((status)) && verdict='**red**'
    printf '### Attestation\n\n'
    printf 'Verified %s (`%s`) against %s.\n\n' "$short" "$branch" "$base_line"
    printf -- '- `scripts/vet.sh all` — %s%s\n' "$verdict" "${url:+ ($url)}"
  fi
  if [ -n "$note" ]; then
    printf '\n'
    cat "$note"
  fi
  printf '\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
} >"$body"

id=$(gh api "repos/$repo/issues/$pr/comments" --paginate \
  --jq '.[] | select(.body | contains("<!-- finalize-attestation")) | .id' | tail -n1) || exit 1
if [ -n "$id" ]; then
  gh api "repos/$repo/issues/comments/$id" -X PATCH -F "body=@$body" --jq .html_url || exit 1
else
  gh pr comment "$pr" --body-file "$body" || exit 1
fi

exit "$status"
