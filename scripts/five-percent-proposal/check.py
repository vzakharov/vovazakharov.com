#!/usr/bin/env python3
"""Whether a `/five-percent` proposal's body is one the operator can read, run before it posts.

The shape is `.claude/skills/five-percent/procedure.md` § "Posting"'s. Only the three visible
lines are held to the reading rules — the fold is for the session that acts on the answer,
and may name anything.

Usage: `python3 scripts/five-percent-proposal/check.py <body-file>...`. Every fault in
every file is printed; the exit status is 1 when any was found.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MARKER = "<!-- five-percent proposal"
HEADER = re.compile(r"\*\*/five-percent\*\* · (optional|critical)")
QUESTION = re.compile(r"\*\*[^*].*\?\*\*")
LABELLED = re.compile(r"[^\s:*`][^:]{0,24}: \S")
FOOTER = ["---", "_Generated by [Claude Code](https://claude.ai/code)_"]
VISIBLE_WORDS_MAX = 60

# Names only the code or the plan gives a thing; the operator's own nouns pass.
JARGON = {
    "a code span": re.compile(r"`"),
    "a link": re.compile(r"https?://"),
    "a path": re.compile(r"\w/\w"),
    "a camelCase name": re.compile(r"\b[a-z]+[A-Z]\w*"),
    "a snake_case name": re.compile(r"\b[A-Za-z]+_[A-Za-z]\w*"),
}


def faults(body: str) -> list[str]:
    """Every way `body` misses the shape; empty when it holds."""
    lines = body.strip("\n").split("\n")
    if len(lines) <= len(FOOTER) or lines[-len(FOOTER) :] != FOOTER or lines[-len(FOOTER) - 1] != "":
        return ["does not end in the footer: a blank line, then `---` and `_Generated by …_`"]
    lines = lines[: -len(FOOTER) - 1]
    fold = next((i for i, line in enumerate(lines) if line.startswith("<details>")), None)
    if fold is not None:
        if lines[-1] != "</details>" or lines[fold - 1] != "":
            return ["the fold is not a blank line, then `<details>` … `</details>` closing the body"]
        lines = lines[: fold - 1]
    if len(lines) < 3 or not lines[0].startswith(MARKER) or not HEADER.fullmatch(lines[1]) or lines[2]:
        return ["does not open on the marker, `**/five-percent** · optional|critical`, and a blank line"]
    visible = lines[3:]
    if len(visible) != 3:
        return [f"has {len(visible)} visible lines after the header, not the question, now and cost"]
    found = []
    question, now, cost = visible
    if not QUESTION.fullmatch(question):
        found.append("the first visible line is not one bold question: `**…?**`")
    for name, line in (("now", now), ("cost", cost)):
        if not LABELLED.match(line):
            found.append(f"the {name} line does not open on a short label and a colon")
    words = len(" ".join(visible).split())
    if words > VISIBLE_WORDS_MAX:
        found.append(f"the visible lines run to {words} words, past {VISIBLE_WORDS_MAX}")
    text = "\n".join(visible)
    for name, pattern in JARGON.items():
        if match := pattern.search(text):
            found.append(f"the visible lines carry {name} ({match.group(0)!r}) — move it into the fold")
    return found


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__.split("\n\n")[-1].strip(), file=sys.stderr)
        return 2
    failed = False
    for name in argv:
        for fault in faults(Path(name).read_text(encoding="utf-8")):
            print(f"{name}: {fault}", file=sys.stderr)
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
