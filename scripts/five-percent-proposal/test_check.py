#!/usr/bin/env python3
"""Holds the proposal check to the shape `.claude/skills/five-percent/procedure.md` § "Posting" spells.

Run by path (`python3 scripts/five-percent-proposal/test_check.py`), as `scripts/vet.sh` does.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from check import faults

HEAD = "<!-- five-percent proposal · an answer here is scored by .claude/skills/five-percent/verdicts.md -->\n**/five-percent** · optional\n\n"
QUESTION = "**Вернуть ui на верх порядка, как в стандартном?**"
NOW = "Сейчас: ui стоит ниже space из-за одного импорта типа с единственным полем."
COST = "Цена: перенести этот тип в space."
FOLD = "\n\n<details><summary>Подробнее</summary>\n\n`Dusked`, `space/repaint-queue.ts`.\n\n</details>"
FOOT = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"


def body(question=QUESTION, now=NOW, cost=COST, fold=FOLD, head=HEAD, foot=FOOT):
    return head + "\n".join(line for line in (question, now, cost) if line is not None) + fold + foot


class ProposalCheckTest(unittest.TestCase):
    def test_the_shape_passes_with_or_without_a_fold(self):
        self.assertEqual(faults(body()), [])
        self.assertEqual(faults(body(fold="")), [])

    def test_the_fold_may_carry_anything(self):
        fold = "\n\n<details><summary>Подробнее</summary>\n\n`segmentOrder` in eslint/masd-graph.ts, https://x.y, a_b\n\n</details>"
        self.assertEqual(faults(body(fold=fold)), [])

    def test_jargon_in_the_visible_lines_fails(self):
        for name, now in {
            "a code span": "Сейчас: тип `Dusked` держит ui внизу.",
            "a path": "Сейчас: space/repaint-queue.ts берёт тип из ui.",
            "a camelCase name": "Сейчас: segmentOrder считает сегментом любую папку.",
            "a snake_case name": "Сейчас: split_agent_footer уже это умеет.",
            "a link": "Сейчас: см. https://github.com/x.",
        }.items():
            with self.subTest(name):
                self.assertTrue(any(name in fault for fault in faults(body(now=now))))

    def test_the_operators_nouns_pass(self):
        now = "Сейчас: правило для src/ говорит «три проверки», а masd.json страницы держится на одной папке; так решил /finalize в #227."
        self.assertEqual(faults(body(now=now)), [])

    def test_a_paragraph_fails(self):
        [fault] = faults(body(question=None, now=None, cost=f"{NOW} {COST}"))
        self.assertIn("1 visible lines", fault)

    def test_a_question_that_is_not_one_fails(self):
        [fault] = faults(body(question="**Перенести тип в space.**"))
        self.assertIn("bold question", fault)

    def test_an_unlabelled_line_fails(self):
        [fault] = faults(body(cost="перенести этот тип в space."))
        self.assertIn("cost line", fault)

    def test_past_the_word_cap_fails(self):
        [fault] = faults(body(now="Сейчас: " + "слово " * 60))
        self.assertIn("words, past 60", fault)

    def test_a_missing_or_doubled_footer_fails(self):
        self.assertIn("footer", faults(body(foot=""))[0])
        doubled = FOOT.rstrip("\n") + "\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n"
        self.assertIn("footer", faults(body(foot=doubled))[0])

    def test_a_missing_header_fails(self):
        self.assertIn("marker", faults(body(head="**/five-percent** · optional\n\n"))[0])


if __name__ == "__main__":
    unittest.main()
