#!/usr/bin/env python3
"""Runs the answered-proposal check's pure half over hand-built comment lists, so no network is touched.

Run by path (`python3 scripts/five-percent-verdicts/test_answered.py`), as `scripts/vet.sh` does.
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from answered import (
    BadPayload,
    PROPOSAL_MARKER,
    parse_head_ref,
    parse_review_comments,
    recorded_ids,
    unrecorded,
)

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def comment(id, body, reply_to=None):
    return {"id": id, "in_reply_to_id": reply_to, "body": body, "html_url": f"https://example.test/r{id}"}


def proposal(id):
    return comment(id, f"{PROPOSAL_MARKER} · scored -->\n**/five-percent** · optional{FOOTER}")


def ids(comments):
    return [c.id for c in comments]


class AnsweredTest(unittest.TestCase):
    def missing(self, payload, recorded=()):
        return ids(unrecorded(parse_review_comments(payload), set(recorded)))

    def test_any_reply_makes_a_proposal_answered(self):
        for body in ("давай", f"Done in abc123.{FOOTER}"):
            with self.subTest(body):
                self.assertEqual(self.missing([proposal(1), comment(2, body, reply_to=1)]), [1])

    def test_a_row_satisfies_an_answered_proposal(self):
        self.assertEqual(self.missing([proposal(1), comment(2, "давай", reply_to=1)], recorded={1}), [])

    def test_an_unanswered_proposal_needs_no_row(self):
        self.assertEqual(self.missing([proposal(1)]), [])

    def test_a_thread_without_the_marker_is_no_proposal(self):
        self.assertEqual(self.missing([comment(1, f"A review note.{FOOTER}"), comment(2, "ok", reply_to=1)]), [])

    def test_the_marker_mid_body_is_no_proposal(self):
        quoted = comment(1, f"See {PROPOSAL_MARKER} above.{FOOTER}")
        self.assertEqual(self.missing([quoted, comment(2, "ok", reply_to=1)]), [])

    def test_malformed_payloads_fail(self):
        cases = {
            "not a list": {"id": 1},
            "bool id": [{**comment(1, "x"), "id": True}],
            "string reply id": [comment(2, "x", reply_to="1")],
            "missing body": [{k: v for k, v in comment(1, "x").items() if k != "body"}],
            "null url": [{**comment(1, "x"), "html_url": None}],
        }
        for name, payload in cases.items():
            with self.subTest(name):
                with self.assertRaises(BadPayload):
                    parse_review_comments(payload)

    def test_head_ref(self):
        self.assertEqual(parse_head_ref({"head": {"ref": "claude/x"}}), "claude/x")
        with self.assertRaises(BadPayload):
            parse_head_ref({"head": {}})


class LedgerTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_a_branch_without_a_file_has_recorded_nothing(self):
        self.assertEqual(recorded_ids(self.root, "claude/none"), set())

    def test_a_slashed_branch_reads_its_nested_file(self):
        path = self.root / "claude/x/verdicts.json"
        path.parent.mkdir(parents=True)
        row = {"comment": 7, "about": "a proposal", "verdict": 1, "why": "taken"}
        path.write_text(json.dumps({"pr": 1, "verdicts": [row]}), encoding="utf-8")
        self.assertEqual(recorded_ids(self.root, "claude/x"), {7})


if __name__ == "__main__":
    unittest.main()
